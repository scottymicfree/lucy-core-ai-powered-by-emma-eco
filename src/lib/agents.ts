// Helper to determine biological mapped lobe based on node LL ID (0-354)
export function getMappedLobe(nodeId: number): string {
  if (nodeId >= 0 && nodeId <= 10) return "Brain Stem (Autonomic / Reflex)";
  if (nodeId === 16 || nodeId === 68 || nodeId === 108 || nodeId === 354) return "Limbic System (Emotion / Priority)";
  if (nodeId >= 8 && nodeId <= 53) return "Temporal Lobe (Memory / Processing)"; // Note overlap is fine, priority cascade
  if (nodeId >= 120 && nodeId <= 137) return "Temporal / Quantum Cortex";
  if (nodeId >= 132 && nodeId <= 137) return "Occipital Lobe (Vision / Pattern)";
  if (nodeId >= 151 && nodeId <= 200) return "Parietal Lobe (Perception / Sensor)";
  if (nodeId >= 201 && nodeId <= 250) return "Frontal Lobe (Executive / Control)";
  if (nodeId >= 351 && nodeId <= 354) return "Frontal Lobe (Curiosity / Executive)";
  if (nodeId >= 251 && nodeId <= 325) return "Cerebellum (Action / Swarm / Builder)";
  
  // Fallbacks based on generalized ranges (LL000-LL119 is classical core, spread across frontal/parietal)
  if (nodeId < 119) return "Frontal Lobe (Reasoning / Core)"; 
  return "Unknown Node Region";
}

export interface SwarmAgent {
  id: string; // LLXXX
  nodeNum: number;
  name: string;
  lobe: string;
  ssScore: number;
}

export interface SecurityTeam {
  id: string;
  name: string;
  securityAgent: string;
  memberCount: number;
  status: 'patrol' | 'luring' | 'pushing' | 'containment';
}

export function generateInitialSwarm(): SwarmAgent[] {
  const agents: SwarmAgent[] = [];
  
  // Create 351 agents
  for (let i = 0; i < 351; i++) {
    const name = RAW_NAMES[i % RAW_NAMES.length];
    const nodeNum = i;
    const id = `LL${nodeNum.toString().padStart(3, '0')}`;
    const ssScore = Math.floor(Math.random() * 800) + 100; // Base Initial Score 100-900

    agents.push({
      id,
      nodeNum,
      name: `${id} ${name}`,
      lobe: getMappedLobe(nodeNum),
      ssScore
    });
  }
  
  return agents;
}

export function generateSecurityTeams(agents: SwarmAgent[]): SecurityTeam[] {
  const teams: SecurityTeam[] = [];
  const numTeams = 7;
  const agentsPerTeam = Math.ceil(agents.length / numTeams);
  
  for (let i=0; i<numTeams; i++) {
    const teamAgents = agents.slice(i * agentsPerTeam, (i+1) * agentsPerTeam);
    if (teamAgents.length === 0) continue;
    
    teams.push({
      id: `TEAM-${i+1}`,
      name: `Squadron ${i+1} [${teamAgents[0].lobe.split(' ')[0]}]`,
      securityAgent: `[SEC-OP] ${teamAgents[0].name.replace(/LL\d{3} /, '')}`,
      memberCount: teamAgents.length,
      status: 'patrol'
    });
  }
  
  return teams;
}
